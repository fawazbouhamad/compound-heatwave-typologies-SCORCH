"""``scorch demo``: a complete small example that runs in about a minute.

``run_demo`` writes a synthetic temperature file with designed heatwave
events (see ``scorch.demo.synthetic``), runs the five SCORCH stages on it,
compares the detected compound events with the design, writes a short
``summary.md`` and, when matplotlib is installed, draws an overview figure.
"""
from __future__ import annotations

import os
import shutil
import subprocess
import time
from pathlib import Path

import pandas as pd

from .. import __version__
from .. import config as cfg
from .. import events as ev
from ..stages import run_stages
from . import synthetic

DEMO_FOLDER_LAYOUT = """\
input/tmax_processed.nc              synthetic temperatures (NetCDF)
input/maps/grid_cells.csv            the demo grid
settings.yml                         the settings used (overrides of the manuscript settings)
output/catalogs/01..05_*/            the five catalogs
output/tables/table_1.csv            compound events by type
output/supporting_results/           intermediate results of every stage
output/figures/demo_overview.png     overview figure (needs matplotlib)
output/run_records/                  what each stage read and wrote, with checksums
summary.md                           this summary
"""


def demo_config(directory, settings_file=None):
    """The settings for a demo in ``directory`` (all files under that folder)."""
    overrides = synthetic.demo_settings()
    overrides["paths"] = {
        "base_dir": str(directory),
        "input_dir": "input",
        "input_file": "tmax_processed.nc",
        "supporting_input_dir": "input",
        "supporting_results_dir": "output/supporting_results",
        "output_dir": "output",
        "run_records_dir": "output/run_records",
    }
    return cfg.load_config(settings_file=settings_file, overrides=overrides)


def write_settings_file(path, directory):
    """Save the demo settings so the run can be repeated with ``scorch run``."""
    import yaml
    settings = synthetic.demo_settings()
    text = (
        "# Settings of the SCORCH demo: the values below override the manuscript\n"
        "# settings (config/manuscript_settings.yml). Repeat the stages with\n"
        f"#   scorch run --settings {path.name} --input-dir input --supporting-input-dir input "
        "--output-dir output\n"
        f"# from the folder {directory}\n"
        + yaml.safe_dump(settings, sort_keys=False, default_flow_style=None))
    path.write_text(text, encoding="utf-8", newline="\n")
    return path


def _markdown_table(table):
    """A Markdown table of a DataFrame without extra dependencies."""
    columns = list(table.columns)
    lines = ["| " + " | ".join(columns) + " |", "|" + "---|" * len(columns)]
    for row in table.itertuples(index=False):
        lines.append("| " + " | ".join("" if pd.isna(v) else str(v) for v in row) + " |")
    return "\n".join(lines)


def write_summary(path, directory, comparison, extra_events, table, selected_days,
                  threshold, figure_path, r_result, seed, seconds):
    n_cells = synthetic.LAT.size * synthetic.LON.size
    lines = [
        "# SCORCH demo summary",
        "",
        f"SCORCH {__version__}, synthetic data seed {seed}, run time {seconds:.0f} s.",
        "",
        "**The temperatures in this demo are invented.** They were generated by",
        "scorch.demo.synthetic so that the workflow can be tried without the",
        "archived ERA5-derived dataset; nothing here describes real heatwaves.",
        "",
        "## What SCORCH did",
        "",
        f"1. Found local heatwaves in each of the {n_cells} cells (3 or more days at or "
        "above the cell's 95th percentile, single cooler days bridged).",
        f"2. Selected the {len(selected_days)} days on which at least {threshold:g} cells were in a "
        "heatwave (the 97.5th percentile of the daily count).",
        "3. Grouped the heatwave cells of each selected day into clusters with DBSCAN.",
        "4. Fitted an ellipse and a temperature-weighted centroid to every cluster.",
        "5. Joined consecutive selected days into compound events and classified them.",
        "",
        "## The four event types",
        "",
    ]
    for t in (1, 2, 3, 4):
        lines.append(f"- **Type {t}, {ev.TYPE_NAMES[t]}**: {ev.TYPE_DESCRIPTIONS[t]}.")
    lines += ["", "## Designed events and what SCORCH found", "",
              "| Designed event | Dates | Expected type | Detected type | Clusters per day | Match |",
              "|---|---|---|---|---|---|"]
    for row in comparison.itertuples():
        detected = row.detected_type if row.detected_type is not None else "not found"
        match = "yes" if row.matches_design else "NO"
        lines.append(f"| {row.designed_event} | {row.dates} | {row.expected_type} | {detected} | "
                     f"{row.daily_cluster_counts} | {match} |")
    if len(extra_events):
        lines += ["", f"SCORCH also found {len(extra_events)} event(s) that were not designed "
                      "(formed by the random weather noise):", ""]
        for row in extra_events.itertuples():
            lines.append(f"- event {row.compound_event_id}: {row.start_date} to {row.end_date}, "
                         f"Type {row.event_type}, clusters per day {row.daily_cluster_counts}")
    else:
        lines += ["", "No other compound events were found: the random weather noise alone never "
                      "produced a regionally extensive heatwave day."]
    lines += ["", "## Table 1 of the demo", "", _markdown_table(table), ""]
    if figure_path:
        relative = figure_path.relative_to(directory).as_posix()
        lines += ["## Figure", "", f"![Demo overview]({relative})", ""]
    if r_result:
        lines += ["## Power-law fit with R", "", r_result, ""]
    lines += ["## Files", "", "```", DEMO_FOLDER_LAYOUT.rstrip(), "```", ""]
    path.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    return path


def find_rscript():
    """Rscript from SCORCH_RSCRIPT, the PATH, or the usual Windows install folders."""
    explicit = os.environ.get("SCORCH_RSCRIPT", "").strip()
    if explicit:
        return explicit
    found = shutil.which("Rscript")
    if found:
        return found
    if os.name == "nt":
        for root in (Path(os.environ.get("ProgramFiles", r"C:\Program Files")) / "R",
                     Path.home() / "AppData" / "Local" / "Programs" / "R"):
            candidates = sorted(root.glob("R-*/bin/Rscript.exe"))
            if candidates:
                return str(candidates[-1])
    return None


def run_r_power_law(repo_root, ellipses_csv, output_csv, log=print):
    """Fit the Clauset power law to the demo ellipse areas with R (optional)."""
    rscript = find_rscript()
    if rscript is None:
        log("Rscript was not found (PATH, SCORCH_RSCRIPT or the usual R install folders); "
            "skipping the R power-law demo")
        return None
    script = repo_root / "demo" / "fit_power_law_demo.R"
    result = subprocess.run([rscript, "--vanilla", str(script), str(ellipses_csv), str(output_csv)],
                            capture_output=True, text=True)
    if result.returncode != 0:
        log("the R power-law demo failed:\n" + result.stderr.strip())
        return None
    log(result.stdout.strip())
    return result.stdout.strip()


def run_demo(directory="demo/run", seed=None, make_figure=True, with_r=False, log=print):
    """Build the synthetic example in ``directory`` and run SCORCH on it."""
    started = time.time()
    seed = synthetic.DEMO_SEED if seed is None else int(seed)
    directory = Path(directory).resolve()
    input_dir = directory / "input"
    log(f"SCORCH {__version__} demo")
    log(f"folder: {directory}")
    log(f"writing synthetic temperatures (seed {seed}) ...")
    synthetic.write_inputs(input_dir, seed)
    settings_path = write_settings_file(directory / "settings.yml", directory)
    config = demo_config(directory)
    results = dict(run_stages(config, log=log))

    output_dir = cfg.output_dir(config)
    catalogs = output_dir / "catalogs"
    events = pd.read_csv(catalogs / "05_compound_heatwave_events" / "compound_events.csv")
    table = pd.read_csv(output_dir / "tables" / "table_1.csv")
    selected = pd.read_csv(catalogs / "02_regionally_extensive_heatwaves" / "selected_days.csv")
    daily = pd.read_csv(cfg.supporting_results_dir(config) / "main_workflow" / "regional_selection"
                        / "daily_summary.csv")
    threshold = float(daily["regional_threshold_cells"].iloc[0])
    comparison, extra, _ = synthetic.compare_with_design(events)

    figure_path = None
    if make_figure:
        try:
            from . import figure
        except ImportError:
            log("matplotlib is not installed; skipping the overview figure "
                "(pip install -e .[figures])")
        else:
            figure_path = figure.draw_overview(config, directory, events, daily, selected,
                                               output_dir / "figures" / "demo_overview.png")
            log(f"figure: {figure_path}")

    r_result = None
    if with_r:
        repo_root = cfg.repository_root()
        if repo_root is None:
            log("the R demo needs a repository checkout (demo/fit_power_law_demo.R)")
        else:
            r_result = run_r_power_law(repo_root,
                                       catalogs / "04_extreme_heatwave_ellipses" / "ellipses.csv",
                                       output_dir / "supporting_results" / "power_law_demo.csv", log)

    seconds = time.time() - started
    summary_path = write_summary(directory / "summary.md", directory, comparison, extra, table,
                                 selected, threshold, figure_path, r_result, seed, seconds)
    log("")
    log(comparison[["designed_event", "dates", "expected_type", "detected_type",
                    "daily_cluster_counts", "matches_design"]].to_string(index=False))
    log("")
    log(f"compound events by type: {results[5]['events_by_type']}")
    log(f"summary: {summary_path}")
    log(f"settings used: {settings_path}")
    log(f"demo finished in {seconds:.0f} s")
    return {"directory": directory, "comparison": comparison, "extra_events": extra,
            "events_by_type": results[5]["events_by_type"], "figure": figure_path,
            "summary": summary_path, "seconds": seconds}
